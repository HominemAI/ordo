//! `ordo introspect --external <schema>.<table>`: the generator for external
//! entities (ruled 2026-11-15, `external-entities`, slice B).
//!
//! Each case makes a foreign table by raw SQL in the conformance cluster,
//! runs the verb as an operator types it, and asserts the text it printed.
//! The loop-closing case then compiles that text with the parser and applies
//! it, and the foreign table is exactly as it was.
//!
//! A regression looks like a block the parser refuses, a `uuid` or `jsonb`
//! column written as a field instead of a comment, a composite primary key
//! taken as a key, or any statement reaching the other system's schema.
//!
//! Databases are prefixed `ordo_xintro_`, one per test function.

use std::path::PathBuf;

mod support;
use ordo_cli::Sources;
use ordo_conformance::Pg;
use support::operator;

fn reset(db: &str, foreign: &str) -> Pg {
    let pg = Pg::named(db);
    pg.exec(&format!(
        "DROP SCHEMA public CASCADE; CREATE SCHEMA public; \
         DROP SCHEMA IF EXISTS crm CASCADE; CREATE SCHEMA crm; {foreign}"
    ))
    .expect("the foreign table");
    pg
}

fn introspect(db: &str, extra: &[&str]) -> operator::Outcome {
    let mut args: Vec<String> = vec!["--db".into(), db.into()];
    args.extend(extra.iter().map(|s| s.to_string()));
    operator::run("introspect", &args)
}

fn one(text: &str) -> Sources {
    Sources::from_parts(vec![("app.ordo".into(), text.to_string())])
}

const CUSTOMERS: &str = r#"
CREATE TABLE crm.customers (
  customer_id bigint PRIMARY KEY,
  full_name   text NOT NULL,
  email       varchar(120),
  age         smallint,
  active      boolean NOT NULL,
  born        date,
  created_at  timestamptz NOT NULL,
  seen_at     timestamp,
  balance     numeric(12,2) NOT NULL,
  note        char(4)
);
"#;

/// Every type in the table of `migration.md` section 2a that a field can
/// have, the key line, and the quoting of names with underscores.
#[test]
fn each_type_in_the_table_maps_and_names_with_underscores_are_quoted() {
    let db = "ordo_xintro_types";
    reset(db, CUSTOMERS);
    let out = introspect(db, &["--external", "crm.customers"]);
    assert_eq!(out.code, 0, "{}", out.report);
    assert_eq!(
        out.report,
        "\
# Generated by `ordo introspect --external crm.customers`. Review it before you apply it.
external customers from crm.customers shared {
  id <- \"customer_id\"
  active: bool <- active
  age: int? <- age
  balance: decimal(2) <- balance
  born: date? <- born
  createdAt: datetime <- \"created_at\"
  email: text? <- email
  fullName: text <- \"full_name\"
  note: text? <- note
  seenAt: datetime? <- \"seen_at\"  # no zone in the column, read as UTC
}
"
    );
}

/// Types with no mapping are comments naming the column and the Postgres
/// type, and the file still parses.
#[test]
fn a_type_with_no_mapping_is_a_comment_and_the_file_still_parses() {
    let db = "ordo_xintro_worklist";
    reset(
        db,
        "CREATE TABLE crm.things (
           id uuid PRIMARY KEY,
           label text NOT NULL,
           meta jsonb,
           blob bytea,
           ratio double precision,
           tags text[],
           ref_id uuid,
           price numeric
         );",
    );
    let out = introspect(db, &["--external", "crm.things"]);
    assert_eq!(out.code, 0, "{}", out.report);
    for expected in [
        "  id: uuid <- id\n",
        "  label: text <- label\n",
        "# unmapped: `meta` is `jsonb`",
        "# unmapped: `blob` is `bytea`",
        "# unmapped: `ratio` is `double precision`",
        "# unmapped: `tags` is `text[]`",
        "# unmapped: `ref_id` is `uuid`",
        "# unmapped: `price` is `numeric`",
    ] {
        assert!(
            out.report.contains(expected),
            "missing `{expected}`:\n{}",
            out.report
        );
    }
    assert!(
        ordo_cli::check_sources(&one(&out.report)).is_ok(),
        "the block compiles:\n{}",
        out.report
    );
}

/// The loop closes: the printed block compiles, applies, and the foreign
/// table is not touched.
#[test]
fn the_printed_block_compiles_and_applies_and_leaves_the_table_alone() {
    let db = "ordo_xintro_loop";
    let pg = reset(
        db,
        &format!("{CUSTOMERS} INSERT INTO crm.customers VALUES (7, 'Ada', 'a@x', 30, true, NULL, now(), NULL, 1.50, 'x');"),
    );
    let before = pg
        .query("SELECT md5(string_agg(c::text, ',' ORDER BY customer_id)) FROM crm.customers c")
        .expect("hash");
    let out = introspect(db, &["--external", "crm.customers"]);
    assert_eq!(out.code, 0, "{}", out.report);

    ordo_cli::check_sources(&one(&out.report)).expect("the parser and sema take the block");

    let dir: PathBuf = std::env::temp_dir().join("ordo-xintro-loop");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("temp dir");
    let path = dir.join("p.ordo");
    std::fs::write(&path, &out.report).expect("write program");
    let applied = operator::run(
        "apply",
        &[
            path.display().to_string(),
            "--db".into(),
            db.into(),
            "--as".into(),
            "test".into(),
        ],
    );
    assert_eq!(applied.code, 0, "{}", applied.report);

    let after = pg
        .query("SELECT md5(string_agg(c::text, ',' ORDER BY customer_id)) FROM crm.customers c")
        .expect("hash");
    assert_eq!(before, after, "the foreign rows are as they were");
    let cols = pg
        .query(
            "SELECT count(*) FROM information_schema.columns \
             WHERE table_schema = 'crm' AND table_name = 'customers'",
        )
        .expect("columns");
    assert_eq!(cols[0][0].as_deref(), Some("10"), "no column was added");
}

/// `--out` writes the file and prints its path.
#[test]
fn out_writes_the_file() {
    let db = "ordo_xintro_out";
    reset(
        db,
        "CREATE TABLE crm.tags (code text PRIMARY KEY, label text);",
    );
    let dir = std::env::temp_dir().join("ordo-xintro-out");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("temp dir");
    let file = dir.join("tags.ordo").display().to_string();
    let out = introspect(db, &["--external", "crm.tags", "--out", &file]);
    assert_eq!(out.code, 0, "{}", out.report);
    assert_eq!(out.report.trim(), file);
    let text = std::fs::read_to_string(&file).expect("the file");
    assert!(text.contains("  id: text <- code\n"), "{text}");
    assert!(text.contains("  label: text? <- label\n"), "{text}");
}

/// `--name` names the entity.
#[test]
fn name_overrides_the_derived_entity_name() {
    let db = "ordo_xintro_name";
    reset(
        db,
        "CREATE TABLE crm.customers (customer_id int PRIMARY KEY, name text);",
    );
    let out = introspect(db, &["--external", "crm.customers", "--name", "patrons"]);
    assert_eq!(out.code, 0, "{}", out.report);
    assert!(
        out.report
            .contains("external patrons from crm.customers shared {"),
        "{}",
        out.report
    );
}

/// A composite primary key is refused `external_no_key`, and `--key` is the
/// way out when a column is unique on its own.
#[test]
fn a_composite_primary_key_is_refused_and_key_names_the_way_out() {
    let db = "ordo_xintro_composite";
    reset(
        db,
        "CREATE TABLE crm.lines (
           order_id int NOT NULL, line_no int NOT NULL, sku text NOT NULL UNIQUE,
           PRIMARY KEY (order_id, line_no)
         );",
    );
    let out = introspect(db, &["--external", "crm.lines"]);
    assert_eq!(out.code, 1, "{}", out.report);
    assert!(out.report.contains("external_no_key"), "{}", out.report);
    assert!(
        out.report.contains("composite (order_id, line_no)"),
        "{}",
        out.report
    );
    assert!(out.report.contains("--key <column>"), "{}", out.report);

    let out = introspect(db, &["--external", "crm.lines", "--key", "sku"]);
    assert_eq!(out.code, 0, "{}", out.report);
    assert!(out.report.contains("  id: text <- sku\n"), "{}", out.report);
    assert!(
        out.report.contains("orderId: int <- \"order_id\""),
        "{}",
        out.report
    );
}

/// No key at all, a `--key` that is not unique, and one that admits null.
#[test]
fn a_table_with_no_key_and_a_bad_key_are_refused() {
    let db = "ordo_xintro_nokey";
    reset(
        db,
        "CREATE TABLE crm.log (at timestamptz, who text, code text UNIQUE);",
    );
    let out = introspect(db, &["--external", "crm.log"]);
    assert_eq!(out.code, 1, "{}", out.report);
    assert!(out.report.contains("external_no_key"), "{}", out.report);
    assert!(out.report.contains("no primary key"), "{}", out.report);

    let out = introspect(db, &["--external", "crm.log", "--key", "who"]);
    assert_eq!(out.code, 1, "{}", out.report);
    assert!(out.report.contains("is not unique"), "{}", out.report);

    let out = introspect(db, &["--external", "crm.log", "--key", "code"]);
    assert_eq!(out.code, 1, "{}", out.report);
    assert!(out.report.contains("admits null"), "{}", out.report);

    let out = introspect(db, &["--external", "crm.log", "--key", "nope"]);
    assert_eq!(out.code, 1, "{}", out.report);
    assert!(out.report.contains("not a column"), "{}", out.report);
}

/// A table that is not there is `external_missing`.
#[test]
fn a_missing_table_is_refused_external_missing() {
    let db = "ordo_xintro_missing";
    reset(db, "CREATE TABLE crm.a (id int PRIMARY KEY);");
    let out = introspect(db, &["--external", "crm.nope"]);
    assert_eq!(out.code, 1, "{}", out.report);
    assert!(out.report.contains("external_missing"), "{}", out.report);
    assert!(out.report.contains("USAGE on `crm`"), "{}", out.report);
}

/// A usage error names the shape, and nothing runs without `--external`.
#[test]
fn the_flags_are_checked() {
    let out = operator::run("introspect", &["--external".into(), "customers".into()]);
    assert_eq!(out.code, 2, "{}", out.report);
    let out = operator::run("introspect", &[]);
    assert_eq!(out.code, 2, "{}", out.report);
    assert!(out.report.contains("--external <schema>.<table>"));
}

/// A column named like a reserved word, or twice after canonical spelling,
/// is a comment, never a broken file.
#[test]
fn a_column_that_cannot_be_a_field_is_a_comment() {
    let db = "ordo_xintro_names";
    reset(
        db,
        "CREATE TABLE crm.odd (
           pk int PRIMARY KEY, id text, full_name text, \"fullName\" text
         );",
    );
    let out = introspect(db, &["--external", "crm.odd"]);
    assert_eq!(out.code, 0, "{}", out.report);
    assert!(out.report.contains("# unmapped: `id`"), "{}", out.report);
    assert!(
        out.report
            .contains("# unmapped: `full_name` would be a second `fullName`")
            || out
                .report
                .contains("# unmapped: `fullName` would be a second `fullName`"),
        "{}",
        out.report
    );
    assert!(
        ordo_cli::check_sources(&one(&out.report)).is_ok(),
        "{}",
        out.report
    );
}
